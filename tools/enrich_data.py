def main() -> int:
    data = json.loads(F.read_text(encoding="utf-8"))
    n_ov = n_cs = n_df = 0
    miss: list[str] = []

    for d in data["diseases"]:
        name = d["name"]
        if "ov" not in d and name in OV:
            d["ov"] = OV[name]
            n_ov += 1
        if "cs" not in d and name in CS:
            d["cs"] = CS[name]
            n_cs += 1
        if name not in OV:
            miss.append(f"病 {name} 缺概述")
        if name not in CS:
            miss.append(f"病 {name} 缺常见症状")

    for sx in data["syndromes"]:
        sid = sx["id"]
        if "df" not in sx and sid in DF:
            sx["df"] = DF[sid]
            n_df += 1
        if sid not in DF:
            miss.append(f"证型 {sid}({sx['n']}) 缺鉴别")

    F.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"已写入：概述 {n_ov} 条、常见症状 {n_cs} 条、鉴别 {n_df} 条")
    if miss:
        print(f"\n仍缺 {len(miss)} 项：")
        for m in miss:
            print("  -", m)
    else:
        print("\n全部补齐")
    return 0


