def main() -> int:
    data = json.loads(F.read_text(encoding="utf-8"))
    changed = 0
    for d in data["diseases"]:
        add = EXPAND.get(d["name"], [])
        before = list(d.get("kw", []))
        for k in add:
            if k not in before:
                before.append(k)
        if before != d.get("kw", []):
            d["kw"] = before
            changed += 1
            print(f"  {d['name']:<8} +{len(before) - len(len and before) if False else len(add)} 个口语词")
    F.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n更新 {changed} 个病种的关键词")
    print("重跑：python tools/build_bundle.py")
    return 0


